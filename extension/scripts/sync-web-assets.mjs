// Run after npm install in web/: node extension/scripts/sync-web-assets.mjs
// Ships static assets only; React and build tools never run in the extension.
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
const root = new URL('../../', import.meta.url);
const require = createRequire(new URL('web/package.json', root));
const React = require('react');
const { renderToStaticMarkup } = require('react-dom/server');
const { transformSync } = require('esbuild');
const read = path => readFileSync(new URL(path, root), 'utf8');
const write = (path, text) => writeFileSync(new URL('extension/' + path, root), text);
const banner = '// Generated by scripts/sync-web-assets.mjs from the website. Do not edit directly.\n';
write('content-guard.js', banner + '(function () {\n' +
  read('web/src/lib/contentGuard.js').replace(/^import FILE_EXTENSIONS[^\n]+/, `const FILE_EXTENSIONS = ${read('backend/app/file_types.json')};`)
    .replace(/export /g, '') + '\nObject.assign(self.Phisang ||= {}, { fileUrlMessage, FILE_MESSAGE });\n})();\n');
for (const [source, target, names] of [
  ['web/src/lib/explanationStream.js', 'stream.js', 'readEventStream, readExplanationStream, readScanStream'],
  ['web/src/lib/copy.js', 'verdicts.js', 'CLASS_META, RISK_BANDS, riskBand, verdictMeta, isHighRisk'],
]) {
  write(target, banner + '(function () {\n' + read(source).replace(/export /g, '') +
    `\nObject.assign(self.Phisang ||= {}, { ${names} });\n})();\n`);
}
const module = { exports: {} };
const compiled = transformSync(read('web/src/components/Banana.jsx'), { loader: 'jsx', format: 'cjs', jsx: 'automatic' }).code;
new Function('require', 'module', 'exports', compiled)(require, module, module.exports);
const art = Object.fromEntries(['benign', 'phishing', 'rotten', 'checking', 'unavailable'].map(state => [state,
  renderToStaticMarkup(React.createElement(module.exports.Banana, { state, width: 120 }), { identifierPrefix: state })]));
write('banana.js', banner + `(function () {
  const art = ${JSON.stringify(art)};
  function renderBanana(container, state, width = 120) {
    if (!container) return;
    container.innerHTML = art[state === 'malware' ? 'rotten' : state] || art.unavailable;
    const svg = container.firstElementChild;
    svg.setAttribute('width', width);
    svg.setAttribute('height', width * 180 / 220);
  }
  Object.assign(self.Phisang ||= {}, { renderBanana });
})();\n`);
write('animations.css', '/* Generated from web/src/index.css. */\n' +
  read('web/src/index.css').split('.banana-scan-fruit {')[1].replace(/^/, '.banana-scan-fruit {').replaceAll('--color-leaf', '--leaf'));
console.log('Synced extension verdicts, stream reader, banana art, and animations.');
